var missingGlyph = [7]string{
	"#####", "#...#", "#...#", "#...#", "#...#", "#...#", "#####",
}

// DrawText paints text at (x, y) in color using the built-in 5x7 font.
// Lowercase letters are folded to uppercase. Glyphs without a mapping
// render as a hollow box. DrawText returns the x coordinate just past the
// last drawn glyph, so callers can chain.
func (c *Canvas) DrawText(x, y int, text string, color Color) int {
	for _, r := range text {
		r = unicode.ToUpper(r)
		glyph, ok := glyphs5x7[r]
		if !ok {
			glyph = missingGlyph
		}
		for row := 0; row < FontHeight; row++ {
			line := glyph[row]
			for col := 0; col < FontWidth && col < len(line); col++ {
				if line[col] == '#' {
					c.Set(x+col, y+row, color)
				}
			}
		}
		x += FontAdvance
	}
	return x
}

// TextWidth returns the pixel width that DrawText would consume for text.
func TextWidth(text string) int {
	n := 0
	for range text {
		n++
	}
	if n == 0 {
		return 0
	}
	return n*FontAdvance - 1
}
